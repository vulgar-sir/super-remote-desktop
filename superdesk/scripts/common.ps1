# Shared helpers for super远程桌面 build scripts (dot-source this file).
$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'

$RepoRoot   = (Resolve-Path "$PSScriptRoot\..\..").Path
$SdHome     = if ($env:SUPERDESK_HOME) { $env:SUPERDESK_HOME } else { 'D:\superdesk' }
$SdTools    = Join-Path $SdHome 'tools'
$SdSrc      = Join-Path $SdHome 'src'        # ASCII-path mirror of the repo, used for builds
$SdOut      = Join-Path $SdHome 'out'
$SecretsDir = Join-Path $RepoRoot 'secrets'
$DistDir    = Join-Path $RepoRoot 'dist'

# Bridge files are generated (git-ignored) and must exist before any build.
$BridgeFiles = @(
    'src\bridge_generated.rs', 'src\bridge_generated.io.rs',
    'flutter\lib\generated_bridge.dart', 'flutter\lib\generated_bridge.freezed.dart',
    'flutter\macos\Runner\bridge_generated.h', 'flutter\ios\Runner\bridge_generated.h'
)

# Flutter's official China mirror: complete (third-party mirrors like TUNA 404 on older releases'
# Dart SDKs) and ~20x faster here than storage.googleapis.com. Override with SUPERDESK_FLUTTER_MIRROR=off.
if ($env:SUPERDESK_FLUTTER_MIRROR -eq 'off') {
    Remove-Item Env:FLUTTER_STORAGE_BASE_URL, Env:PUB_HOSTED_URL -ErrorAction SilentlyContinue
} else {
    $env:FLUTTER_STORAGE_BASE_URL = 'https://storage.flutter-io.cn'
    $env:PUB_HOSTED_URL = 'https://pub.flutter-io.cn'
}
# vcpkg's WinHTTP downloader rejects "::1" in the proxy bypass list.
foreach ($v in 'no_proxy', 'NO_PROXY') {
    $cur = [Environment]::GetEnvironmentVariable($v, 'Process')
    if ($cur) { [Environment]::SetEnvironmentVariable($v, (($cur -split '[,;]' | Where-Object { $_ -and $_ -ne '::1' }) -join ','), 'Process') }
}

function Step($name) { Write-Host "`n=== $name ===" -ForegroundColor Cyan }

function Invoke-Native {
    # Run a native command (first arg) and throw on non-zero exit. Simple function on purpose:
    # args like "-f" must pass through untouched instead of binding as PowerShell parameters.
    $exe = $args[0]
    $rest = @($args | Select-Object -Skip 1)
    & $exe @rest
    if ($LASTEXITCODE) { throw "$exe exited with $LASTEXITCODE" }
}

# Build-time client config for a flavor (secrets/superdesk.json + superdesk/flavors.json), as env vars.
function Get-SuperdeskBuildEnv([string]$Flavor = 'full') {
    $prev = [Console]::OutputEncoding
    [Console]::OutputEncoding = [Text.UTF8Encoding]::new($false)
    try { $lines = & python "$PSScriptRoot\make_build_env.py" $Flavor }
    finally { [Console]::OutputEncoding = $prev }
    if ($LASTEXITCODE) { throw "make_build_env.py failed for flavor $Flavor" }
    $envs = [ordered]@{}
    foreach ($l in $lines) { $i = $l.IndexOf('='); $envs[$l.Substring(0, $i)] = $l.Substring($i + 1) }
    $envs
}

function Get-SuperdeskVersion {
    (Select-String -Path (Join-Path $RepoRoot 'Cargo.toml') -Pattern '^version = "(.+)"' |
        Select-Object -First 1).Matches[0].Groups[1].Value
}

# Mirror the repo to an ASCII build path. Build outputs on the mirror side are kept.
# Windows and Android builds use separate mirrors so they can run at the same time.
function Sync-Source([string]$Dest = $SdSrc) {
    Step "Sync source -> $Dest"
    New-Item -ItemType Directory -Force $Dest | Out-Null
    $xd = @('.git', 'target', 'build', '.dart_tool', 'ephemeral', '.gradle', 'jniLibs',
            'vcpkg_installed', 'secrets', 'dist', 'node_modules')
    # version.rs: generated by build.rs, which only reruns when Cargo.toml changes -- never purge it.
    $xf = @('*不准放入git仓库*', '.flutter-plugins', '.flutter-plugins-dependencies', 'key.properties',
            'rustdesk-*.exe', 'SuperDesk-*.exe', 'version.rs')
    robocopy $RepoRoot $Dest /MIR /NFL /NDL /NJH /NP /R:1 /W:1 /XD @xd /XF @xf | Out-Null
    if ($LASTEXITCODE -ge 8) { throw "robocopy failed ($LASTEXITCODE)" }
    $global:LASTEXITCODE = 0
    $ver = Join-Path $Dest 'src\version.rs'
    if (-not (Test-Path $ver)) {
        $v = Get-SuperdeskVersion
        [IO.File]::WriteAllText($ver, "pub const VERSION: &str = `"$v`";`n#[allow(dead_code)]`npub const BUILD_DATE: &str = `"$(Get-Date -Format 'yyyy-MM-dd HH:mm')`";`n")
    }
}

function Test-BridgeFiles {
    foreach ($f in $BridgeFiles) { if (-not (Test-Path (Join-Path $RepoRoot $f))) { return $false } }
    return $true
}
