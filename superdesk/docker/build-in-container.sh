#!/usr/bin/env bash
# Runs inside the superdesk-builder image (see builder.Dockerfile).
#   build-in-container.sh bridge                 -> bridge files into /out/bridge
#   build-in-container.sh android <abi>          -> APK into /out   (abi: arm64-v8a|armeabi-v7a|x86_64)
#   build-in-container.sh keygen                 -> Android signing key into /secrets/android
# Mounts: /src  source tree (read-only)
#         /work persistent volume: synced source + cargo target, for incremental builds
#         /out  outputs        /secrets  git-ignored secrets dir (keygen/android only)
set -euo pipefail
MODE=${1:?usage: bridge | android <abi> | keygen}

sync_src() {
    mkdir -p /work/src
    rsync -a --delete \
        --exclude=/.git --exclude=/target --exclude=/secrets --exclude='*不准放入git仓库*' \
        --exclude=/flutter/build --exclude=/flutter/.dart_tool \
        --exclude=/flutter/.flutter-plugins --exclude=/flutter/.flutter-plugins-dependencies \
        --exclude=/flutter/android/.gradle --exclude=/flutter/android/key.properties \
        --exclude=/flutter/android/app/src/main/jniLibs --exclude=/src/version.rs \
        /src/ /work/src/
    cd /work/src
    # Generated by build.rs, which only reruns when Cargo.toml changes: recreate it if missing.
    if [ ! -f src/version.rs ]; then
        printf 'pub const VERSION: &str = "%s";\n#[allow(dead_code)]\npub const BUILD_DATE: &str = "%s";\n' \
            "$(grep -m1 '^version = ' Cargo.toml | cut -d'"' -f2)" "$(date '+%Y-%m-%d %H:%M')" > src/version.rs
    fi
}

case "$MODE" in
bridge)
    sync_src
    export PATH=/opt/flutter-3.22.3/bin:$PATH
    # Same as CI (bridge.yml): Flutter 3.22.3 needs extended_text 13 to resolve; no vcpkg.
    sed -i -e 's/extended_text: 14.0.0/extended_text: 13.0.0/g' flutter/pubspec.yaml
    (cd flutter && retry flutter pub get)
    env -u VCPKG_ROOT flutter_rust_bridge_codegen \
        --rust-input ./src/flutter_ffi.rs \
        --dart-output ./flutter/lib/generated_bridge.dart \
        --c-output ./flutter/macos/Runner/bridge_generated.h
    cp ./flutter/macos/Runner/bridge_generated.h ./flutter/ios/Runner/bridge_generated.h
    rm -rf /out/bridge
    for f in src/bridge_generated.rs src/bridge_generated.io.rs \
             flutter/lib/generated_bridge.dart flutter/lib/generated_bridge.freezed.dart \
             flutter/macos/Runner/bridge_generated.h flutter/ios/Runner/bridge_generated.h; do
        mkdir -p "/out/bridge/$(dirname "$f")"
        cp "$f" "/out/bridge/$f"
    done
    echo "BRIDGE OK"
    ;;

keygen)
    mkdir -p /secrets/android
    if [ -f /secrets/android/superdesk.jks ]; then echo "key exists, not overwriting"; exit 0; fi
    PASS=$(head -c 24 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 24)
    keytool -genkeypair -keystore /secrets/android/superdesk.jks -alias superdesk \
        -keyalg RSA -keysize 2048 -validity 36500 -storepass "$PASS" -keypass "$PASS" \
        -dname "CN=SuperDesk, O=SuperDesk"
    printf 'storePassword=%s\nkeyPassword=%s\nkeyAlias=superdesk\nstoreFile=/secrets/android/superdesk.jks\n' \
        "$PASS" "$PASS" > /secrets/android/key.properties
    echo "KEYGEN OK"
    ;;

android)
    ABI=${2:-arm64-v8a}
    case "$ABI" in
        arm64-v8a)   TARGET=aarch64-linux-android;   NDKLIB=aarch64-linux-android; FPLAT=android-arm64; FEAT=flutter,hwcodec ;;
        armeabi-v7a) TARGET=armv7-linux-androideabi; NDKLIB=arm-linux-androideabi; FPLAT=android-arm;   FEAT=flutter,hwcodec ;;
        x86_64)      TARGET=x86_64-linux-android;    NDKLIB=x86_64-linux-android;  FPLAT=android-x64;   FEAT=flutter ;;
        *) echo "unknown abi $ABI" >&2; exit 1 ;;
    esac
    : "${SUPERDESK_RENDEZVOUS_SERVER:?missing SUPERDESK_* build env}"
    sync_src
    export PATH=/opt/flutter-3.24.5/bin:$PATH
    # Full LTO of librustdesk needs more RAM than the Docker VM has; thin LTO is close enough.
    export CARGO_PROFILE_RELEASE_LTO=${CARGO_PROFILE_RELEASE_LTO:-thin}
    retry cargo ndk --platform 21 --target "$TARGET" build --locked --release --features "$FEAT"

    JNI=flutter/android/app/src/main/jniLibs/$ABI
    rm -rf flutter/android/app/src/main/jniLibs && mkdir -p "$JNI"
    cp "target/$TARGET/release/liblibrustdesk.so" "$JNI/librustdesk.so"
    cp "$ANDROID_NDK_HOME/toolchains/llvm/prebuilt/linux-x86_64/sysroot/usr/lib/$NDKLIB/libc++_shared.so" "$JNI/"

    sed -i "s/org.gradle.jvmargs=-Xmx1024M/org.gradle.jvmargs=-Xmx2g/g" flutter/android/gradle.properties
    if [ "${SUPERDESK_GRADLE_MIRROR:-aliyun}" = aliyun ]; then
        # Rewrite Google Maven / Maven Central / plugin portal to the Aliyun mirrors (all repos, all scopes).
        mkdir -p /root/.gradle/init.d
        cat > /root/.gradle/init.d/superdesk-mirrors.gradle <<'EOF'
def swap = { repo ->
    if (!(repo instanceof MavenArtifactRepository)) return
    def u = repo.url.toString()
    if (u.startsWith('https://dl.google.com/dl/android/maven2')) repo.url = 'https://maven.aliyun.com/repository/google'
    else if (u.startsWith('https://repo.maven.apache.org/maven2') || u.startsWith('https://repo1.maven.org/maven2')) repo.url = 'https://maven.aliyun.com/repository/public'
    else if (u.startsWith('https://plugins.gradle.org/m2')) repo.url = 'https://maven.aliyun.com/repository/gradle-plugin'
}
gradle.beforeSettings { s -> s.pluginManagement.repositories.all(swap); s.dependencyResolutionManagement.repositories.all(swap) }
allprojects { buildscript.repositories.all(swap); repositories.all(swap) }
EOF
    else
        rm -f /root/.gradle/init.d/superdesk-mirrors.gradle
    fi
    if [ -f /secrets/android/key.properties ]; then
        cp /secrets/android/key.properties flutter/android/key.properties
    else
        echo "WARN: no signing key, using debug signing" >&2
        sed -i "s/signingConfigs.release/signingConfigs.debug/g" flutter/android/app/build.gradle
    fi

    VERSION=$(grep -m1 '^version = ' Cargo.toml | cut -d'"' -f2)
    (cd flutter && retry flutter build apk --release --target-platform "$FPLAT" --split-per-abi)
    NAME="${SUPERDESK_APP_NAME}-${VERSION}-${SUPERDESK_BUILD}-android-${ABI}.apk"
    rm -f /out/*.apk /out/*.apk.json
    cp "flutter/build/app/outputs/flutter-apk/app-$ABI-release.apk" "/out/$NAME"
    printf '{"platform":"android","flavor":"%s","version":"%s","build":"%s","file":"%s","abi":"%s","display_name":"%s"}\n' \
        "$SUPERDESK_FLAVOR" "$VERSION" "$SUPERDESK_BUILD" "$NAME" "$ABI" "$SUPERDESK_DISPLAY_NAME" > "/out/$NAME.json"
    echo "APK OK: $NAME"
    ;;
*)
    echo "unknown mode $MODE" >&2; exit 1 ;;
esac
